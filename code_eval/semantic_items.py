@dataclass(frozen=True)
class Example:
    """설계 기준표의 PASS/FAIL 예시 한 쪽. ``quote`` 는 FAIL 예시의 '평가 모델 인용'(답변 원문 그대로)."""

    kind: str          # PASS | FAIL
    question: str
    answer: str
    note: str          # 표의 설명 문장
    quote: str = ""    # FAIL 예시의 평가 모델 인용 — 반드시 answer 안에 글자 그대로 있다
    history: str = ""  # J6 예시의 '이전 턴' 원문

    def to_dict(self) -> Dict[str, str]:
        return {"kind": self.kind, "question": self.question, "history": self.history, "answer": self.answer,
                "note": self.note, "quote": self.quote}


@dataclass(frozen=True)
class SemanticSub:
    id: str             # J1-1 … J6-4
    criterion: str      # J1 … J6
