def _items_of_sub(sub_id: str) -> List[str]:
    return [item.id for item in ITEMS if item.sub == sub_id]


def applicable_items(case: Dict[str, Any], applicability: Optional[Dict[str, Any]] = None,
                     conversation: Optional[Dict[str, Any]] = None) -> List[Tuple[SemanticItem, Dict[str, Any]]]:
    """이 질문에 보낼 항목과 적용 근거 — [(SemanticItem, {rules, matches, excerpt, source, …}), …] (기준표 순서).

    ``applicability`` 는 ``sub_applicability`` 결과(세부 기준 ID 키) 또는 그것을 ``subs`` 키에 담은 적용 판정 dict 이다.
    없으면 case 의 질문·답변·reference 와 ``conversation`` 으로 직접 계산한다. 세부 기준 항목의 ``items`` 목록이
    빈 세부 기준은 보내지 않고, 목록이 없는 세부 기준은 그 항목 전부를 보낸다. 답변과 무관하게 질문이 정한다
    (J5-3.a 만 답변에서 생긴 항목이라 답변에 따라 달라질 수 있다).
    """
    subs = applicability.get("subs") if isinstance(applicability, dict) and isinstance(applicability.get("subs"), dict) else applicability
    if not isinstance(subs, dict):
        from .jev_applicability import sub_applicability   # 지연 import — 데이터 모듈은 규칙 모듈에 의존하지 않는다
        subs = sub_applicability(case.get("question") or "", case.get("answer"), reference=case.get("reference"),
                                 conversation=conversation, answer_tools=case.get("answer_tools") or "unknown",
                                 history=case.get("history"))
    chosen: List[Tuple[SemanticItem, Dict[str, Any]]] = []
    for item in ITEMS:
        entry = subs.get(item.sub)
        if not isinstance(entry, dict):
            continue
        enabled = entry.get("items")
        if enabled is None:
            enabled = _items_of_sub(item.sub)
        if item.id not in enabled:
            continue
        chosen.append((item, dict(entry)))
    return chosen


def describe() -> Dict[str, Any]:
    """registry·화면용 기준 정의 (판정 로직 없음)."""
    return {
        "version": SEMANTIC_ITEMS_VERSION,
        "subs": [{"id": s.id, "criterion": s.criterion, "name": s.name, "applies_when": s.applies_when} for s in SUBS],
        "items": [{"id": it.id, "sub": it.sub, "criterion": it.criterion, "question": it.question, "applies": it.applies,
                   "evidence": it.evidence, "expand": it.expand, "expand_limit": it.expand_limit if it.expand else None,
                   "missing_type": it.missing_type, "origin": it.origin, "always": it.always,
                   "model_applies": it.model_applies, "fact_block": it.fact_block,
                   "examples": [ex.to_dict() for ex in it.examples]} for it in ITEMS],
        "overrides": [{"trigger": trigger, "when": when, "not_applicable": list(targets)} for trigger, when, targets in OVERRIDES],
        "listing_rules": list(LISTING_RULES),
        "reason_codes": list(REASON_CODE_PRIORITY),
    }


